import re
from collections import Counter


# =========================================================
# 韩中游戏本地化 - 格式 QA
#
# 目的：
# AI 翻译完成以后，不依赖 AI 自己判断格式是否正确。
# 必须由 Python 再执行一次程序级硬检查。
#
# 当前重点保护：
#
# {0} {1} {name}
# %s %d %1$s
# \n \t \r
# <br>
# HTML / XML / 颜色标签
# [SYSTEM_ID] 等方括号标识
# $VARIABLE
# URL
# 邮箱
# 数字
# 百分比
# 实际换行
# 实际 Tab
#
# 注意：
# 正式翻译规则仍以 agent_rules.py 为最高规则来源。
# 本文件只负责“格式完整性”的程序级检查。
# =========================================================


# =========================================================
# 正则规则
# =========================================================


# ---------------------------------------------------------
# {0}
# {1}
# {name}
# ---------------------------------------------------------

CURLY_PLACEHOLDER_PATTERN = re.compile(
    r"\{[^{}\r\n]+\}"
)


# ---------------------------------------------------------
# printf 风格变量：
#
# %s
# %d
# %f
# %1$s
# %02d
# %.2f
# %%
# ---------------------------------------------------------

PRINTF_PATTERN = re.compile(
    r"%(?:\d+\$)?"
    r"[-+0# ]*"
    r"\d*"
    r"(?:\.\d+)?"
    r"[diuoxXfFeEgGaAcspn%]"
)


# ---------------------------------------------------------
# HTML / XML / 游戏标签：
#
# <br>
# <color=red>
# </color>
# <font=...>
# ---------------------------------------------------------

TAG_PATTERN = re.compile(
    r"<[^<>]+>"
)


# ---------------------------------------------------------
# 字面转义符：
#
# \n
# \t
# \r
# \\
# ---------------------------------------------------------

ESCAPE_PATTERN = re.compile(
    r"\\(?:n|t|r|\\)"
)


# ---------------------------------------------------------
# 方括号标识：
#
# [SYSTEM]
# [ITEM_ID]
# [Quest_01]
# [abc:def]
#
# 这里只检测偏程序/标识符风格的方括号内容。
# ---------------------------------------------------------

BRACKET_IDENTIFIER_PATTERN = re.compile(
    r"\[[A-Za-z0-9_.:/=\-]+\]"
)


# ---------------------------------------------------------
# $variable
# ---------------------------------------------------------

DOLLAR_VARIABLE_PATTERN = re.compile(
    r"\$[A-Za-z_][A-Za-z0-9_]*"
)


# ---------------------------------------------------------
# URL
# ---------------------------------------------------------

URL_PATTERN = re.compile(
    r"https?://[^\s<>\"']+",
    re.IGNORECASE,
)


# ---------------------------------------------------------
# Email
# ---------------------------------------------------------

EMAIL_PATTERN = re.compile(
    r"[A-Za-z0-9._%+\-]+"
    r"@[A-Za-z0-9.\-]+"
    r"\.[A-Za-z]{2,}"
)


# ---------------------------------------------------------
# 百分比：
#
# 10%
# 10％
# 12.5%
# 1,000%
# -10%
# +20%
# ---------------------------------------------------------

PERCENT_PATTERN = re.compile(
    r"[-+]?"
    r"(?:\d{1,3}(?:,\d{3})+|\d+)"
    r"(?:\.\d+)?"
    r"\s*[%％]"
)


# ---------------------------------------------------------
# 普通数字
#
# 重要：
#
# 这里不能使用 \w 作为左右边界，
# 因为 Python 的 \w 会把中文、韩文也视为“单词字符”。
#
# 如果使用：
#
#     (?![\w])
#
# 那么：
#
#     200金币
#
# 中的 200 会被漏掉。
#
# 所以这里只禁止数字紧邻 ASCII 英文/数字/下划线。
#
# 可以正确识别：
#
# 100 골드
# 100골드
# 100金币
# 레벨100
# 5회
# 10개
#
# 同时尽量避免把 abc123 之类代码中的数字
# 当成普通数值。
# ---------------------------------------------------------

NUMBER_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_])"
    r"[-+]?"
    r"(?:\d{1,3}(?:,\d{3})+|\d+)"
    r"(?:\.\d+)?"
    r"(?![A-Za-z0-9_])"
)


# =========================================================
# 基础工具
# =========================================================

def normalize_percent(value):
    """
    QA 比较时：

    10%
    10％

    视为同一个百分比。

    同时去掉数字与 % 之间的普通空格。
    """

    value = str(
        value
    )

    value = value.replace(
        "％",
        "%"
    )

    value = re.sub(
        r"\s+%",
        "%",
        value,
    )

    return value


# =========================================================
# Counter 比较
# =========================================================

def compare_counter(
    source_items,
    target_items
):
    """
    比较原文与译文 Token。

    不仅比较有没有，
    还比较出现次数。

    例如：

    原文：
    {0} ... {0}

    译文只有一个：
    {0}

    仍然会判定缺失一个。
    """

    source_counter = Counter(
        source_items
    )

    target_counter = Counter(
        target_items
    )


    missing = list(
        (
            source_counter
            -
            target_counter
        ).elements()
    )


    extra = list(
        (
            target_counter
            -
            source_counter
        ).elements()
    )


    return (
        missing,
        extra,
    )


# =========================================================
# 提取格式 Token
# =========================================================

def extract_format_tokens(text):
    """
    从文本中提取所有需要程序保护的格式信息。
    """

    text = str(
        text or ""
    )


    # =====================================================
    # 花括号占位符
    # =====================================================

    curly = (
        CURLY_PLACEHOLDER_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # printf
    # =====================================================

    printf = (
        PRINTF_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # HTML / XML / 游戏标签
    # =====================================================

    tags = (
        TAG_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # 字面转义符
    # =====================================================

    escapes = (
        ESCAPE_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # 方括号程序标识
    # =====================================================

    bracket_ids = (
        BRACKET_IDENTIFIER_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # $变量
    # =====================================================

    dollar_variables = (
        DOLLAR_VARIABLE_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # URL
    # =====================================================

    urls = (
        URL_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # Email
    # =====================================================

    emails = (
        EMAIL_PATTERN
        .findall(
            text
        )
    )


    # =====================================================
    # 百分比
    # =====================================================

    percentages = [

        normalize_percent(
            item
        )

        for item in
        PERCENT_PATTERN.findall(
            text
        )
    ]


    # =====================================================
    # 普通数字
    #
    # 在提取普通数字之前，
    # 先把其他特殊格式 Token 移除。
    #
    # 这样避免：
    #
    # {0}
    # 中的 0
    #
    # %1$s
    # 中的 1
    #
    # URL中的数字
    #
    # 被再次当作普通数字。
    # =====================================================

    number_text = text


    patterns_to_remove = [

        URL_PATTERN,

        EMAIL_PATTERN,

        CURLY_PLACEHOLDER_PATTERN,

        PRINTF_PATTERN,

        TAG_PATTERN,

        ESCAPE_PATTERN,

        BRACKET_IDENTIFIER_PATTERN,

        DOLLAR_VARIABLE_PATTERN,

        PERCENT_PATTERN,
    ]


    for pattern in patterns_to_remove:

        number_text = pattern.sub(
            "",
            number_text,
        )


    numbers = (
        NUMBER_PATTERN
        .findall(
            number_text
        )
    )


    # =====================================================
    # 返回
    # =====================================================

    return {

        "花括号占位符":
            curly,

        "Printf变量":
            printf,

        "HTML/XML标签":
            tags,

        "转义符":
            escapes,

        "方括号标识":
            bracket_ids,

        "变量":
            dollar_variables,

        "URL":
            urls,

        "邮箱":
            emails,

        "百分比":
            percentages,

        "数字":
            numbers,

        # 真正存在于字符串中的换行
        "实际换行数":
            text.count(
                "\n"
            ),

        # 真正存在于字符串中的 Tab
        "实际Tab数":
            text.count(
                "\t"
            ),
    }


# =========================================================
# 比较一个 Token 类别
# =========================================================

def compare_category(
    source_tokens,
    target_tokens,
    category
):
    """
    检查某一类 Token：

    - 原文有，译文没有
    - 原文没有，译文新增
    """

    missing, extra = (
        compare_counter(
            source_tokens,
            target_tokens,
        )
    )


    issues = []


    # =====================================================
    # 译文缺失
    # =====================================================

    if missing:

        issues.append(
            {
                "类型":
                    category,

                "问题":
                    "译文缺失",

                "内容":
                    "、".join(
                        missing
                    ),
            }
        )


    # =====================================================
    # 译文新增
    # =====================================================

    if extra:

        issues.append(
            {
                "类型":
                    category,

                "问题":
                    "译文新增",

                "内容":
                    "、".join(
                        extra
                    ),
            }
        )


    return issues


# =========================================================
# 主格式检查
# =========================================================

def check_format(
    source_text,
    translated_text
):
    """
    比较韩文原文与中文译文的格式结构。

    返回示例：

    {
        "通过": True,
        "问题数量": 0,
        "问题": [],
        "原文格式": {...},
        "译文格式": {...}
    }
    """

    source = extract_format_tokens(
        source_text
    )

    target = extract_format_tokens(
        translated_text
    )


    issues = []


    # =====================================================
    # 必须严格一致的类别
    # =====================================================

    categories = [

        "花括号占位符",

        "Printf变量",

        "HTML/XML标签",

        "转义符",

        "方括号标识",

        "变量",

        "URL",

        "邮箱",

        "百分比",

        "数字",
    ]


    # =====================================================
    # 逐类比较
    # =====================================================

    for category in categories:

        issues.extend(
            compare_category(
                source[
                    category
                ],
                target[
                    category
                ],
                category,
            )
        )


    # =====================================================
    # 实际换行数量
    # =====================================================

    if (
        source[
            "实际换行数"
        ]
        !=
        target[
            "实际换行数"
        ]
    ):

        issues.append(
            {
                "类型":
                    "实际换行",

                "问题":
                    "数量不一致",

                "内容":
                    (
                        f"原文 "
                        f"{source['实际换行数']} 个；"
                        f"译文 "
                        f"{target['实际换行数']} 个"
                    ),
            }
        )


    # =====================================================
    # 实际 Tab 数量
    # =====================================================

    if (
        source[
            "实际Tab数"
        ]
        !=
        target[
            "实际Tab数"
        ]
    ):

        issues.append(
            {
                "类型":
                    "实际Tab",

                "问题":
                    "数量不一致",

                "内容":
                    (
                        f"原文 "
                        f"{source['实际Tab数']} 个；"
                        f"译文 "
                        f"{target['实际Tab数']} 个"
                    ),
            }
        )


    # =====================================================
    # 返回完整检查结果
    # =====================================================

    return {

        "通过":
            len(
                issues
            )
            ==
            0,

        "问题数量":
            len(
                issues
            ),

        "问题":
            issues,

        "原文格式":
            source,

        "译文格式":
            target,
    }


# =========================================================
# 简洁 QA 文本
# =========================================================

def format_qa_summary(
    source_text,
    translated_text
):
    """
    生成适合 Streamlit / Excel 显示的结果。

    通过：

    通过

    不通过：

    不通过：数字译文缺失：100；数字译文新增：200
    """

    result = check_format(
        source_text,
        translated_text
    )


    # =====================================================
    # 没有问题
    # =====================================================

    if result[
        "通过"
    ]:

        return "通过"


    # =====================================================
    # 生成错误说明
    # =====================================================

    messages = []


    for issue in result[
        "问题"
    ]:

        message = (
            f"{issue['类型']}"
            f"{issue['问题']}"
        )


        content = issue.get(
            "内容",
            ""
        )


        if content:

            message += (
                f"：{content}"
            )


        messages.append(
            message
        )


    return (
        "不通过："
        +
        "；".join(
            messages
        )
    )


# =========================================================
# 是否有格式风险
# =========================================================

def has_format_risk(
    source_text,
    translated_text
):
    """
    只要出现任何格式异常，
    就返回 True。
    """

    result = check_format(
        source_text,
        translated_text
    )

    return not result[
        "通过"
    ]


